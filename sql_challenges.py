def verify_challenge_solution(engine, user_sql: str, challenge: Dict[str, Any]) -> Dict[str, Any]:
    """
    Executes the user's SQL and the expected reference SQL on the engine,
    and performs automated dataset comparison.
    """
    user_res = engine.execute_query(user_sql)
    if not user_res.is_success:
        return {
            "passed": False,
            "error": f"SQL Execution Error: {user_res.error}",
            "user_res": user_res,
            "expected_res": None
        }

    expected_res = engine.execute_query(challenge["expected_sql"])
    if not expected_res.is_success:
        return {
            "passed": False,
            "error": f"Reference query error: {expected_res.error}",
            "user_res": user_res,
            "expected_res": expected_res
        }

    # Compare column counts
    if len(user_res.columns) != len(expected_res.columns):
        return {
            "passed": False,
            "error": f"Column count mismatch: Expected {len(expected_res.columns)} columns, but got {len(user_res.columns)}.",
            "user_res": user_res,
            "expected_res": expected_res
        }

    # Compare row counts
    if user_res.row_count != expected_res.row_count:
        return {
            "passed": False,
            "error": f"Row count mismatch: Expected {expected_res.row_count} rows, but got {user_res.row_count} rows.",
            "user_res": user_res,
            "expected_res": expected_res
        }

    # Compare row values (normalized as tuples of strings to prevent minor float rounding issues)
    def normalize_row(row):
        norm = []
        for val in row:
            if isinstance(val, float):
                norm.append(round(val, 2))
            else:
                norm.append(str(val).strip() if val is not None else "NULL")
        return tuple(norm)

    norm_user = [normalize_row(r) for r in user_res.rows]
    norm_expected = [normalize_row(r) for r in expected_res.rows]

    if norm_user != norm_expected:
        return {
            "passed": False,
            "error": "Dataset values mismatch: Output rows do not match expected results.",
            "user_res": user_res,
            "expected_res": expected_res
        }

    return {
        "passed": True,
        "error": None,
        "user_res": user_res,
        "expected_res": expected_res
    }
